// Telemetry stream generator for charts
export function generateSensorReadings(shipmentId: string): SensorReading[] {
  const shipment = mockShipments.find(s => s.id === shipmentId) || mockShipments[0];
  const readings: SensorReading[] = [];
  const baseTemp = (shipment.targetTempMin + shipment.targetTempMax) / 2;
  const now = new Date('2026-09-04T23:00:00Z').getTime();
  
  // Generate 24 hours of data points at 30-min intervals
  for (let i = 48; i >= 0; i--) {
    const timeMs = now - (i * 30 * 60 * 1000);
    const dateIso = new Date(timeMs).toISOString();

    // Create a gap in the middle if shipment has gaps
    const isGapPeriod = shipment.gapCount > 0 && (i >= 16 && i <= 24);

    let temp = baseTemp + (Math.sin(i / 3) * 0.4) + (Math.random() * 0.3 - 0.15);
    
    // Simulate excursion for critical shipment
    if (shipment.id === 'shp-104' && i <= 20) {
      temp = -11.2 + (Math.random() * 0.5);
    } else if (shipment.id === 'shp-101' && i >= 16 && i <= 24) {
      temp = 2.1 + (Math.random() * 0.3);
    }

    const currentTempNum = Number(temp.toFixed(2));
    readings.push({
      id: `rdg-${shipmentId}-${i}`,
      shipment_id: shipmentId,
      sensor_id: shipment.sensorIds[0] || 'sns-301',
      timestamp: dateIso,
      ground_truth_temperature: currentTempNum,
      observed_temperature: isGapPeriod ? null : currentTempNum,
      temperature: currentTempNum,
      humidity: 85 + Math.floor(Math.random() * 10),
      shock: 0.05,
      tilt: 0.0,
      latitude: 6.9271,
      longitude: 79.8612,
      signal_strength: isGapPeriod ? -118 : -65,
      battery_level: 90 - Math.floor((48 - i) / 5),
      connectivity_status: isGapPeriod ? 'Offline' : 'Connected',
      status: isGapPeriod ? 'Dropped' : 'Observed',
      clock_skew_seconds: 12,
      leg_name: shipment.currentLeg,
      sensorId: shipment.sensorIds[0] || 'sns-301',
      shipmentId,
      isObserved: !isGapPeriod,
      isReconstructed: isGapPeriod,
      locationName: isGapPeriod ? `${shipment.currentLeg} (Gap Sector)` : `${shipment.currentLeg}`,
    });
  }

  return readings;
}
